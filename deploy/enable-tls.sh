#!/usr/bin/env bash
# Issue a Let's Encrypt certificate and switch nginx to HTTPS 443.
#
#   ./deploy/enable-tls.sh example.com you@example.com
#
# Needs: DNS A/AAAA for the domain pointing at this host, port 80 open, docker.
# Idempotent: safe to re-run (certbot reuses the existing lineage). Renewal is
# handled by deploy/daily-jobs.sh cert; nothing here is a daily job.
set -euo pipefail

DOMAIN="${1:?usage: enable-tls.sh <domain> [email]}"
EMAIL="${2:-}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

mkdir -p deploy/certbot-www deploy/tls deploy/tls-sites

# 1. Certificate (webroot validation — nginx keeps serving during issuance).
docker run --rm \
    -v "$ROOT/deploy/tls:/etc/letsencrypt" \
    -v "$ROOT/deploy/certbot-www:/var/www/certbot" \
    certbot/certbot certonly --webroot -w /var/www/certbot \
    -d "$DOMAIN" --non-interactive --agree-tos --no-eff-email \
    ${EMAIL:+-m "$EMAIL"}

# 2. TLS server block. Routes come from nginx-app.conf, so there is nothing to
#    duplicate: port 80 redirects, port 443 serves the same app.
cat > "deploy/tls-sites/${DOMAIN}.conf" <<EOF
server {
    listen 80;
    server_name ${DOMAIN};

    location /.well-known/acme-challenge/ {
        root /var/www/certbot;
    }
    location / {
        return 308 https://\$host\$request_uri;
    }
}

server {
    listen 443 ssl;
    http2 on;
    server_name ${DOMAIN};

    ssl_certificate     /etc/nginx/tls/live/${DOMAIN}/fullchain.pem;
    ssl_certificate_key /etc/nginx/tls/live/${DOMAIN}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:tls:10m;
    add_header Strict-Transport-Security "max-age=31536000" always;

    include /etc/nginx/app-locations.conf;
}
EOF

# 3. Publish 443 and reload.
cat > deploy/compose.tls.yaml <<EOF
# Generated by enable-tls.sh — adds the HTTPS port. Keep both files together
# for every compose command: -f deploy/compose.prod.yaml -f deploy/compose.tls.yaml
services:
  nginx:
    ports:
      - "443:443"
EOF

docker compose -f deploy/compose.prod.yaml -f deploy/compose.tls.yaml up -d nginx
docker compose -f deploy/compose.prod.yaml -f deploy/compose.tls.yaml exec -T nginx nginx -s reload
echo "HTTPS enabled for ${DOMAIN}. Renewal: deploy/daily-jobs.sh cert"
