test('manual post upload creates a ready saved record without claiming scheduling', async ({ page, request }) => {
  await signIn(page, '/content', 'Content')
  await page.getByRole('button', { name: 'New manual post' }).click()
  const dialog = page.getByRole('dialog', { name: 'New manual post' })
  await dialog.getByLabel('Platform').selectOption('x')
  await dialog.getByLabel('Destination URL').fill('https://example.test/offer')
  await dialog.getByLabel('CTA label').fill('Read the guide')
  await dialog.getByLabel('Media').setInputFiles('tests/e2e/contacts.spec.ts-snapshots/contacts-desktop-linux.png')
  await dialog.getByRole('button', { name: 'Save manual post' }).click()
  await expect(page.getByRole('status')).toContainText('Manual post saved and ready')
  const response = await request.get('/company/ui/content', { headers: { Authorization: auth } })
  expect(response.status()).toBe(200)
  const saved = (await response.json()).items.find((item: { kind: string; stage: string; asset_count: number; platform: string }) => item.kind === 'manual_post' && item.stage === 'ready' && item.asset_count === 1 && item.platform === 'x')
  expect(saved).toBeTruthy()
  expect(saved.stage).toBe('ready')
  expect(saved.buffer_status).toBe('not_started')
})

