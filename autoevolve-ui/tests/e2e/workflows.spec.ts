test('Outreach approval stops at authorization and then refreshes the backend record', async ({ page, request }) => {
  await signIn(page, '/outreach', 'Outreach')
  await page.getByRole('row', { name: /Rift Dynamics/ }).click()
  const drawer = page.getByRole('complementary', { name: 'Outreach details' })
  await drawer.getByLabel('Founder action token').fill('wrong')
  await drawer.getByRole('button', { name: 'Approve draft' }).click()
  await expect(drawer.getByRole('alert')).toContainText('not authorized')
  await drawer.getByLabel('Founder action token').fill('browser-action')
  await drawer.getByRole('button', { name: 'Approve draft' }).click()
  await expect(drawer.getByRole('status')).toContainText('Draft approved')
  await expect(drawer.getByRole('button', { name: 'Send approved email' })).toBeVisible()
  const id = new URL(page.url()).searchParams.get('draft')
  const response = await request.get(`/company/ui/outreach/${id}`, { headers: { Authorization: auth } })
  expect(response.status()).toBe(200)
  expect((await response.json()).status).toBe('approved')
})

test('workflow read failures stay visible and 401 ends the session', async ({ page }) => {
  await signIn(page, '/campaigns', 'Campaigns')
  await page.route('**/company/ui/campaigns?*', route => route.fulfill({ status: 500, body: JSON.stringify({ detail: 'fixture failure' }), contentType: 'application/json' }))
  await page.getByPlaceholder('Search campaigns or objectives…').fill('failure')
  await expect(page.getByRole('heading', { name: 'Campaigns could not be loaded' })).toBeVisible()
  await expect(page.getByText('No campaigns found')).not.toBeVisible()
  await page.unroute('**/company/ui/campaigns?*')
  await page.route('**/company/ui/campaigns?*', route => route.fulfill({ status: 401, body: JSON.stringify({ detail: 'Unauthorized' }), contentType: 'application/json' }))
  await page.getByPlaceholder('Search campaigns or objectives…').fill('session')
  await expect(page.getByLabel('Username')).toBeVisible()
})

test('Buffer configuration and insights failures stop the action without hiding saved content', async ({ page }) => {
  await page.route('**/company/marketing/buffer-accounts', route => route.fulfill({
    status: 200, contentType: 'application/json',
    body: JSON.stringify({ accounts: [{ name: 'default', organization_id: null, instagram_channel_id: false, x_channel_id: false }], error: 'G3 reported no Buffer accounts' }),
  }))
  await signIn(page, '/content', 'Content')
  await page.getByRole('row', { name: /Modern Ops with AI/ }).click()
  let drawer = page.getByRole('complementary', { name: 'Content details' })
  await expect(drawer.getByRole('alert')).toContainText('G3 reported no Buffer accounts')
  await expect(drawer.getByRole('button', { name: 'Schedule post' })).toBeDisabled()
  await drawer.getByRole('button', { name: 'Close content details' }).click()
  await page.route('**/company/marketing/manual-posts/*/buffer-insights?*', route => route.fulfill({
    status: 502, contentType: 'application/json', body: JSON.stringify({ detail: 'Buffer provider unavailable' }),
  }))
  await page.getByRole('row', { name: /Published Provider Example/ }).click()
  drawer = page.getByRole('complementary', { name: 'Content details' })
  await expect(drawer.getByRole('alert')).toContainText('Buffer provider unavailable')
  await expect(drawer.getByText('A saved manual post with a confirmed Buffer ID.')).toBeVisible()
})

test('campaign and asset creation persist queued records; Buffer scheduling respects authorization and refreshes state', async ({ page, request }) => {
  await signIn(page, '/campaigns', 'Campaigns')
  await page.getByRole('button', { name: 'New campaign' }).click()
  const modal = page.getByRole('dialog', { name: 'New campaign' })
  await modal.getByLabel('Brief').fill('Help operations teams automate repetitive work')
  await modal.getByRole('button', { name: 'Create campaign' }).click()
  await expect(page.getByRole('status')).toContainText('Campaign accepted by the backend')
  await expect(page.getByRole('complementary', { name: 'Campaign details' })).toContainText('queued')
  const campaignId = new URL(page.url()).searchParams.get('campaign')
  const campaign = await request.get(`/company/ui/campaigns/${campaignId}`, { headers: { Authorization: auth } })
  expect(campaign.status()).toBe(200)
  expect((await campaign.json()).status).toBe('queued')

  await page.getByLabel('Main navigation').getByRole('link', { name: 'Content' }).click()
  await page.getByRole('button', { name: 'New asset pack' }).click()
  const assetModal = page.getByRole('dialog', { name: 'New asset pack' })
  await assetModal.getByLabel('Script').fill('A complete source script describing practical automation for operations teams.')
  await assetModal.getByRole('button', { name: 'Queue asset pack' }).click()
  await expect(page.getByRole('status')).toContainText('Asset pack queued by the backend')
  const content = await request.get('/company/ui/content', { headers: { Authorization: auth } })
  expect(content.status()).toBe(200)
  expect((await content.json()).items.some((item: { kind: string; stage: string }) => item.kind === 'asset_pack' && item.stage === 'queued')).toBe(true)

  await page.getByRole('row', { name: /Modern Ops with AI/ }).click()
  const drawer = page.getByRole('complementary', { name: 'Content details' })
  await drawer.getByLabel('Founder action token').fill('wrong')
  await drawer.getByRole('button', { name: 'Schedule post' }).click()
  await expect(drawer.getByRole('alert')).toContainText('not authorized')
  await drawer.getByLabel('Founder action token').fill('browser-action')
  await drawer.getByRole('button', { name: 'Schedule post' }).click()
  await expect(drawer.getByRole('status')).toContainText('Buffer scheduling confirmed by the backend')
  await expect(drawer).toContainText('scheduled')
  const refreshed = await request.get('/company/ui/content', { headers: { Authorization: auth } })
  expect(refreshed.status()).toBe(200)
  expect((await refreshed.json()).items.find((item: { title: string }) => item.title === 'Modern Ops with AI').buffer_status).toBe('scheduled')
})

